import type { ComponentDefinition } from "./component-registry/contracts.ts";
import {
  PROJECT_WORKFLOW_ACTION_TYPES,
  PROJECT_WORKFLOW_ROUTES,
  type ProjectWorkflowActionType,
} from "./db/project-workflow-contract.ts";
import { PREBUILT_MODULES_LIBRARY_SOURCE } from "./generation/prebuilt-modules-library.ts";

const AI_STORY_COMPONENT_TYPES = [
  "AmoebaStory",
  "FlowFieldStory",
  "HeatMapStory",
  "HoneycombStory",
  "NetworkWebStory",
  "PulseWaveStory",
  "SpiralStory",
  "TerrainStory",
] as const;

const AI_WORKFLOW_ACTION_GUIDANCE: Record<ProjectWorkflowActionType, string> = {
  triggerToast: 'params: { body: string, duration: { kind: "preset", value: "short" | "long" | "infinite" } or { kind: "seconds", value: 1..300 }, icon?: string }.',
  showModal: 'params: { modalComponentKey: string }; the key must identify a Modal in this project.',
  saveToTable: 'params: { sourceFormComponentKey: string, targetTable: { tableType, resourceKey, catalog, schema, table, plus the selected Lakebase identity fields when applicable }, excludedColumns: [{ columnName, reason: "autogenerated" | "systemManaged" | "manualSkip" }], columnMappings: [{ formChildComponentKey, targetColumnName }] }. The source must be the workflow Form trigger.',
  buildSql: 'params: { sqlSourceKind: "unityCatalogTable" | "lakebaseProvisionedDatabase" | "lakebaseAutoscaling", sqlTemplate: string, placeholders: [{ token, componentKey, valueType: "string" | "number" | "boolean" | "date" | "datetime" | "unknown", formatHint?: "raw" | "sqlStringLiteral" | "sqlIdentifier" | "dateLiteral" }] }. Optional Lakebase resource/database names apply to Lakebase; sqlWarehouseId and sqlWarehouseName are an optional pair for Unity Catalog SQL.',
  runSql: 'params: { statement: { sourceActionType: "buildSql", nodeId: string } }; reference an earlier or routed predecessor BuildSql node in this workflow.',
  setBinding: 'params: { source: { sourceActionType: "runSql", nodeId: string, outputKey: "rows" }, target: { componentKey: string, bindingType: "unityCatalogTable" | "chartData" } }; the target must be a compatible table or chart component.',
  startDatabricksJob: 'params: { job: { resourceType: "databricksJob", resourceKey: string, jobName: string } }; use only an already selected current-workspace Job reference.',
  callCustomModule: 'params: { functionName: string }; the project module must define a top-level synchronous function whose first parameter is ctx and which can be called with ctx alone.',
  callPrebuiltModule: 'params: { functionName: string, namedArguments: Record<string, string> }; the argument names must match the selected prebuilt signature exactly.',
};

/** Builds exact workflow, event, story, and prebuilt-module guidance from active contracts. */
export function buildAiBuilderContractGuidance(
  componentDefinitions: ComponentDefinition[],
): string {
  const eventMap = componentDefinitions
    .filter((definition) => definition.supportedEvents && definition.supportedEvents.length > 0)
    .map((definition) => `${definition.type}: ${definition.supportedEvents?.join(", ")}`)
    .join("; ");
  const actionGuidance = PROJECT_WORKFLOW_ACTION_TYPES
    .map((actionType) => `- ${actionType}: ${AI_WORKFLOW_ACTION_GUIDANCE[actionType]}`)
    .join("\n");
  const prebuiltSignatures = PREBUILT_MODULES_LIBRARY_SOURCE
    .split("\n")
    .filter((line) => /^def [A-Za-z_][A-Za-z0-9_]*\(/.test(line))
    .join("\n");
  const stories = AI_STORY_COMPONENT_TYPES.filter((type) =>
    componentDefinitions.some((definition) => definition.type === type))
    .join(", ");

  return [
    "Workflow contract:",
    `- Action types and exact params: ${PROJECT_WORKFLOW_ACTION_TYPES.join(", ")}.`,
    actionGuidance,
    `- Workflow routes are exactly: ${PROJECT_WORKFLOW_ROUTES.join(", ")}. Node IDs must be unique; routes stay within one workflow.`,
    `- Trigger event map from the active component registry: ${eventMap}. Use only a listed component type/event pair.`,
    `- Prebuilt module signatures from the active library:\n${prebuiltSignatures || "(none)"}`,
    `Story visualizations: ${stories}. Choose only a story the user requested. Preserve each selected type's registry property names and mapping roles. Map only to fields already present in project bindings; if the source or role is unclear, ask the user to choose a resource or field in the editor before proposing the workflow or visualization.`,
    "Resource authority: project sharing does not grant Databricks resource access. Never invent catalog, schema, table, Volume, warehouse, Lakebase, endpoint, Genie space, or Job IDs/names. Reuse only references already present in the supplied project; ask the user to select a new workspace resource in VDAB first.",
  ].join("\n");
}
