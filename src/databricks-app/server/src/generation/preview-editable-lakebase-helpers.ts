/** Adds viewer-authorized transactional writes for Lakebase EditableDataWindow tables. */
export function appendEditableLakebaseHelpers(lines: string[]): void {
  lines.push(
    "",
    "def _vdab_lakebase_edit_value(value: object) -> object:",
    "    if value is None:",
    "        return None",
    "    try:",
    "        missing = pd.isna(value)",
    "        if not hasattr(missing, '__iter__') and bool(missing):",
    "            return None",
    "    except (TypeError, ValueError):",
    "        pass",
    "    if hasattr(value, 'item'):",
    "        value = value.item()",
    "    if hasattr(value, 'read') or hasattr(value, 'getbuffer') or isinstance(value, (dict, list, tuple, set)):",
    "        raise RuntimeError('Lakebase table edits accept only scalar values.')",
    "    if isinstance(value, float) and not math.isfinite(value):",
    "        raise RuntimeError('Lakebase table edits cannot save non-finite numbers.')",
    "    if isinstance(value, str) and len(value) > 10000:",
    "        raise RuntimeError('Lakebase table edit values exceed the supported size.')",
    "    return value",
    "",
    "async def _vdab_lakebase_save_editable_rows_async(source_kind: str, schema: str, table: str, database: str, endpoint: str, instance_name: str, primary_key: str, columns: list[str], changes: list[dict[str, object]], resource_environment_variable: str) -> None:",
    "    if source_kind == 'lakebaseAutoscaling':",
    "        settings = _vdab_lakebase_connection_settings(database, endpoint, resource_environment_variable)",
    "    elif source_kind == 'lakebaseProvisionedDatabase':",
    "        settings = _vdab_lakebase_provisioned_connection_settings(database, instance_name, resource_environment_variable)",
    "    else:",
    "        raise RuntimeError('EditableDataWindow requires a supported Lakebase database.')",
    "    settings['server_settings'] = {}",
    "    if not columns or len(columns) > 100 or len(changes) > 500 or primary_key not in columns or len(set(columns)) != len(columns):",
    "        raise RuntimeError('The saved Lakebase editable table metadata is invalid.')",
    "    if any(not isinstance(name, str) or not name or len(name) > 255 for name in [schema, table, primary_key, *columns]):",
    "        raise RuntimeError('The saved Lakebase editable table identifiers are invalid.')",
    "    quoted_schema = _vdab_postgres_sql(_vdab_quote_sql_identifier(schema))",
    "    quoted_table = _vdab_postgres_sql(_vdab_quote_sql_identifier(table))",
    "    target = quoted_schema + '.' + quoted_table",
    "    quoted_columns = {name: _vdab_postgres_sql(_vdab_quote_sql_identifier(name)) for name in columns}",
    "    key_column = quoted_columns[primary_key]",
    "    update_columns = [name for name in columns if name != primary_key]",
    "    update_assignments = ', '.join(quoted_columns[name] + ' = $' + str(index + 1) for index, name in enumerate(update_columns))",
    "    insert_columns = ', '.join(quoted_columns[name] for name in columns)",
    "    insert_values = ', '.join('$' + str(index + 1) for index in range(len(columns)))",
    "    payload_bytes = len(json.dumps(changes, default=str, ensure_ascii=False, separators=(',', ':')).encode('utf-8'))",
    "    if payload_bytes > 5000000:",
    "        raise RuntimeError('This Lakebase table change is too large to save safely.')",
    "    connection = None",
    "    try:",
    "        connection = await asyncpg.connect(**settings)",
    "        async with connection.transaction():",
    "            await connection.execute('LOCK TABLE ' + target + ' IN SHARE ROW EXCLUSIVE MODE')",
    "            statistics = await connection.fetchrow('SELECT COUNT(*) AS total_rows, COUNT(' + key_column + ') AS non_null_rows, COUNT(DISTINCT ' + key_column + ') AS unique_rows FROM ' + target)",
    "            if statistics is None or int(statistics['total_rows']) != int(statistics['non_null_rows']) or int(statistics['total_rows']) != int(statistics['unique_rows']):",
    "                raise RuntimeError('The selected primary key must be unique and non-null across the whole Lakebase table before saving.')",
    "            for change in changes:",
    "                if not isinstance(change, dict) or change.get('operation') not in ('upsert', 'delete') or not isinstance(change.get('row'), dict) or set(change['row']) != set(columns):",
    "                    raise RuntimeError('The Lakebase table change set does not match the saved table schema.')",
    "                row = {name: _vdab_lakebase_edit_value(change['row'][name]) for name in columns}",
    "                if row[primary_key] is None:",
    "                    raise RuntimeError('Lakebase primary key values must not be null.')",
    "                if change['operation'] == 'delete':",
    "                    await connection.execute('DELETE FROM ' + target + ' WHERE ' + key_column + ' = $1', row[primary_key])",
    "                    continue",
    "                if update_columns:",
    "                    update_values = [row[name] for name in update_columns] + [row[primary_key]]",
    "                    status = await connection.execute('UPDATE ' + target + ' SET ' + update_assignments + ' WHERE ' + key_column + ' = $' + str(len(update_columns) + 1), *update_values)",
    "                    if int(status.rsplit(' ', 1)[-1]) > 0:",
    "                        continue",
    "                await connection.execute('INSERT INTO ' + target + ' (' + insert_columns + ') VALUES (' + insert_values + ')', *(row[name] for name in columns))",
    "    except asyncpg.PostgresError:",
    "        raise RuntimeError('Lakebase denied or rejected the current viewer edit. Check the postgres scope and viewer role grants.') from None",
    "    except (asyncpg.exceptions.InterfaceError, OSError, TimeoutError):",
    "        raise RuntimeError('The Lakebase PostgreSQL endpoint could not be reached safely.') from None",
    "    finally:",
    "        if connection is not None:",
    "            await connection.close()",
    "",
    "def _vdab_lakebase_save_editable_rows(source_kind: str, schema: str, table: str, database: str, endpoint: str, instance_name: str, primary_key: str, columns: list[str], changes: list[dict[str, object]], resource_environment_variable: str) -> None:",
    "    try:",
    "        asyncio.run(_vdab_lakebase_save_editable_rows_async(source_kind, schema, table, database, endpoint, instance_name, primary_key, columns, changes, resource_environment_variable))",
    "    except RuntimeError:",
    "        raise",
    "    except Exception:",
    "        raise RuntimeError('Lakebase could not complete the current viewer edit.') from None",
    "",
  );
}
