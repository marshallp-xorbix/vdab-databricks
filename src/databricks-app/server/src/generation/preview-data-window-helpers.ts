const SQL_HTTP_RESPONSE_LIMIT_BYTES = 5_000_000;
const SQL_RESULT_LIMIT_BYTES = 20_000_000;
const SQL_RESULT_ROW_LIMIT = 10_000;
const SQL_RESULT_CHUNK_LIMIT = 100;

/** Appends generated SQL helpers used by Unity Catalog data components. */
export function appendDataWindowHelpers(lines: string[]): void {
  appendSqlRequestHelpers(lines);
  appendSqlExecutionHelper(lines);
  appendSqlMergeHelper(lines);
  appendSqlValueHelper(lines);
  appendTableDiffHelpers(lines);
  appendDataWindowQuerySetup(lines);
  appendDataWindowQueryResults(lines);
  appendPrimaryKeyValidationHelper(lines);
}

/** Appends only read helpers for generated visualizations without editable tables. */
export function appendDataWindowReadHelpers(lines: string[]): void {
  appendSqlRequestHelpers(lines);
  appendDataWindowQuerySetup(lines);
  appendDataWindowQueryResults(lines);
}

function appendSqlRequestHelpers(lines: string[]): void {
  lines.push(
    "",
    `_VDAB_SQL_MAX_HTTP_RESPONSE_BYTES = ${SQL_HTTP_RESPONSE_LIMIT_BYTES}`,
    `_VDAB_SQL_MAX_RESULT_BYTES = ${SQL_RESULT_LIMIT_BYTES}`,
    `_VDAB_SQL_MAX_RESULT_ROWS = ${SQL_RESULT_ROW_LIMIT}`,
    `_VDAB_SQL_MAX_RESULT_CHUNKS = ${SQL_RESULT_CHUNK_LIMIT}`,
    "",
    "def _vdab_sql_request(method: str, path: str, body: dict[str, object] | None = None) -> tuple[dict[str, object], int]:",
    "    user_token = st.context.headers.get('x-forwarded-access-token')",
    "    if not user_token:",
    "        raise RuntimeError('The current viewer did not grant Databricks SQL user authorization.')",
    "    workspace_host = os.environ.get('DATABRICKS_HOST', '')",
    "    parsed_host = urllib.parse.urlsplit(workspace_host)",
    "    if parsed_host.scheme != 'https' or not parsed_host.netloc or parsed_host.username or parsed_host.password or parsed_host.path not in ('', '/') or parsed_host.query or parsed_host.fragment:",
    "        raise RuntimeError('The Databricks workspace host is not configured safely.')",
    "    request_body = None if body is None else json.dumps(body).encode('utf-8')",
    "    request = urllib.request.Request(",
    "        f'{parsed_host.scheme}://{parsed_host.netloc}{path}',",
    "        data=request_body,",
    "        headers={'Authorization': f'Bearer {user_token}', 'Accept': 'application/json', 'Content-Type': 'application/json'},",
    "        method=method,",
    "    )",
    "    try:",
    "        with _vdab_open_no_redirect(request) as response:",
    "            response_bytes = response.read(_VDAB_SQL_MAX_HTTP_RESPONSE_BYTES + 1)",
    "        if len(response_bytes) > _VDAB_SQL_MAX_HTTP_RESPONSE_BYTES:",
    "            raise RuntimeError('The Databricks SQL response is too large to load safely.')",
    "        response_body = json.loads(response_bytes.decode('utf-8'))",
    "    except urllib.error.HTTPError as error:",
    "        if error.code in (401, 403):",
    "            raise RuntimeError('SQL access denied. Check the current viewer’s sql authorization, warehouse access, and required table permissions.') from None",
    "        raise RuntimeError(f'Databricks rejected the SQL request (HTTP {error.code}).') from None",
    "    except TimeoutError:",
    "        raise RuntimeError('The Databricks SQL API request timed out.') from None",
    "    except urllib.error.URLError:",
    "        raise RuntimeError('The Databricks SQL API could not be reached.') from None",
    "    except (UnicodeDecodeError, json.JSONDecodeError):",
    "        raise RuntimeError('Databricks returned an invalid SQL response.') from None",
    "    if not isinstance(response_body, dict):",
    "        raise RuntimeError('Databricks returned an invalid SQL response.')",
    "    return response_body, len(response_bytes)",
    "",
    "def _vdab_quote_sql_identifier(value: str) -> str:",
    "    return '`' + value.replace('`', '``') + '`'",
    "",
    "def _vdab_sql_result_part(response_body: dict[str, object]) -> dict[str, object]:",
    "    result_part = response_body.get('result', response_body)",
    "    if not isinstance(result_part, dict):",
    "        raise RuntimeError('Databricks returned an invalid SQL result.')",
    "    return result_part",
    "",
    "def _vdab_sql_reject_truncated_result(response_body: dict[str, object]) -> None:",
    "    if response_body.get('truncated') is True:",
    "        raise RuntimeError('The Databricks SQL result was truncated by its configured row or byte limit.')",
    "",
  );
}

function appendSqlExecutionHelper(lines: string[]): void {
  lines.push(
    "def _vdab_sql_execute(statement: str, parameters: list[dict[str, str | None]]) -> None:",
    "    warehouse_id = os.environ.get('DATABRICKS_SQL_WAREHOUSE_ID', '')",
    "    if not re.fullmatch(r'[A-Za-z0-9_-]{1,128}', warehouse_id):",
    "        raise RuntimeError('Bind an existing SQL warehouse to this app before saving table changes.')",
    "    response_body, _response_bytes = _vdab_sql_request('POST', '/api/2.0/sql/statements', {",
    "        'statement': statement, 'warehouse_id': warehouse_id, 'parameters': parameters,",
    "        'wait_timeout': '30s', 'on_wait_timeout': 'CONTINUE', 'disposition': 'INLINE',",
    "    })",
    "    statement_id = response_body.get('statement_id')",
    "    if not isinstance(statement_id, str) or not re.fullmatch(r'[A-Za-z0-9-]{1,128}', statement_id):",
    "        raise RuntimeError('Databricks returned an invalid SQL statement identifier.')",
    "    status_part = response_body.get('status')",
    "    if not isinstance(status_part, dict):",
    "        raise RuntimeError('Databricks returned an invalid SQL statement status.')",
    "    state = status_part.get('state')",
    "    for _poll_attempt in range(12):",
    "        if state == 'SUCCEEDED':",
    "            return",
    "        if state not in ('PENDING', 'RUNNING'):",
    "            raise RuntimeError('Databricks denied or failed the SQL change. Check the current viewer’s sql scope, warehouse access, and table MODIFY permission.')",
    "        time.sleep(1)",
    "        statement_path = '/api/2.0/sql/statements/' + urllib.parse.quote(statement_id, safe='')",
    "        statement_path += '?warehouse_id=' + urllib.parse.quote(warehouse_id, safe='')",
    "        response_body, _response_bytes = _vdab_sql_request('GET', statement_path)",
    "        status_part = response_body.get('status')",
    "        if not isinstance(status_part, dict):",
    "            raise RuntimeError('Databricks returned an invalid SQL statement status.')",
    "        state = status_part.get('state')",
    "    raise RuntimeError('The Databricks SQL change timed out before it completed.')",
    "",
  );
}

function appendSqlMergeHelper(lines: string[]): void {
  lines.push(
    "def _vdab_sql_merge_rows(catalog: str, schema: str, table: str, columns: list[tuple[str, str]], primary_key: str, changes: list[dict[str, object]]) -> None:",
    "    if len(columns) < 1 or len(columns) > 100 or len(changes) > 500:",
    "        raise RuntimeError('This table change exceeds the safe editable row or column limit.')",
    "    column_names = [column[0] for column in columns]",
    "    if len(set(column_names)) != len(column_names) or primary_key not in column_names:",
    "        raise RuntimeError('The saved editable table metadata is invalid.')",
    "    safe_types = {'BOOLEAN', 'TINYINT', 'SMALLINT', 'INT', 'BIGINT', 'FLOAT', 'DOUBLE', 'DATE', 'TIMESTAMP', 'TIMESTAMP_NTZ', 'STRING'}",
    "    for name, sql_type in columns:",
    "        if not isinstance(name, str) or not name or not isinstance(sql_type, str) or (sql_type not in safe_types and not re.fullmatch(r'DECIMAL\\([1-9][0-9]?,[0-9]{1,2}\\)', sql_type)):",
    "            raise RuntimeError('The saved editable table column metadata is invalid.')",
    "    json_rows = []",
    "    for change in changes:",
    "        if not isinstance(change, dict) or change.get('operation') not in ('upsert', 'delete') or not isinstance(change.get('row'), dict):",
    "            raise RuntimeError('The table change set is invalid.')",
    "        row = change['row']",
    "        if set(row) != set(column_names):",
    "            raise RuntimeError('The table change does not match the saved table columns.')",
    "        json_row = {'op': change['operation']}",
    "        for column_index, column_name in enumerate(column_names):",
    "            json_row['c' + str(column_index)] = _vdab_sql_text_value(row[column_name])",
    "        json_rows.append(json_row)",
    "    payload = json.dumps(json_rows, ensure_ascii=False, separators=(',', ':'))",
    "    if len(payload.encode('utf-8')) > 5_000_000:",
    "        raise RuntimeError('This table change is too large to save in one atomic SQL statement.')",
    "    schema_fields = ['op: STRING'] + ['c' + str(index) + ': STRING' for index in range(len(columns))]",
    "    selected_columns = ['payload.op AS `__vdab_op`']",
    "    selected_columns.extend('CAST(payload.c' + str(index) + ' AS ' + sql_type + ') AS ' + _vdab_quote_sql_identifier(name) for index, (name, sql_type) in enumerate(columns))",
    "    source_sql = 'SELECT ' + ', '.join(selected_columns)",
    "    source_sql += \" FROM (SELECT explode(from_json(:changes, 'ARRAY<STRUCT<\" + ', '.join(schema_fields) + \">>')) AS payload) AS changes\"",
    "    target = '.'.join(_vdab_quote_sql_identifier(name) for name in (catalog, schema, table))",
    "    key = _vdab_quote_sql_identifier(primary_key)",
    "    statement = 'MERGE INTO ' + target + ' AS target USING (' + source_sql + ') AS source ON target.' + key + ' = source.' + key",
    "    statement += \" WHEN MATCHED AND source.`__vdab_op` = 'delete' THEN DELETE\"",
    "    update_columns = [name for name in column_names if name != primary_key]",
    "    if update_columns:",
    "        assignments = ', '.join('target.' + _vdab_quote_sql_identifier(name) + ' = source.' + _vdab_quote_sql_identifier(name) for name in update_columns)",
    "        statement += \" WHEN MATCHED AND source.`__vdab_op` = 'upsert' THEN UPDATE SET \" + assignments",
    "    target_columns = ', '.join(_vdab_quote_sql_identifier(name) for name in column_names)",
    "    source_columns = ', '.join('source.' + _vdab_quote_sql_identifier(name) for name in column_names)",
    `    statement += " WHEN NOT MATCHED AND source.\`__vdab_op\` = 'upsert' THEN INSERT (" + target_columns + ') VALUES (' + source_columns + ')'`,
    "    _vdab_sql_execute(statement, [{'name': 'changes', 'type': 'STRING', 'value': payload}])",
    "",
  );
}

function appendSqlValueHelper(lines: string[]): void {
  lines.push(
    "def _vdab_sql_text_value(value: object) -> str | None:",
    "    if value is None:",
    "        return None",
    "    try:",
    "        missing = pd.isna(value)",
    "        if not hasattr(missing, '__iter__') and bool(missing):",
    "            return None",
    "    except (TypeError, ValueError):",
    "        pass",
    "    if hasattr(value, 'item'):",
    "        value = value.item()",
    "    if hasattr(value, 'isoformat'):",
    "        return value.isoformat()",
    "    if isinstance(value, bool):",
    "        return 'true' if value else 'false'",
    "    return str(value)",
    "",
  );
}

function appendTableDiffHelpers(lines: string[]): void {
  lines.push(
    "def _vdab_diff_table(original: pd.DataFrame, edited: pd.DataFrame, primary_key: str, column_names: list[str]) -> list[dict[str, object]]:",
    "    if primary_key not in column_names or list(original.columns) != column_names or list(edited.columns) != column_names:",
    "        raise RuntimeError('The edited table no longer matches its saved schema.')",
    "    original_rows = original.to_dict(orient='records')",
    "    edited_rows = edited.to_dict(orient='records')",
    "    original_by_key = _vdab_rows_by_key(original_rows, primary_key)",
    "    edited_by_key = _vdab_rows_by_key(edited_rows, primary_key)",
    "    changes = []",
    "    for row_key, row in original_by_key.items():",
    "        if row_key not in edited_by_key:",
    "            changes.append({'operation': 'delete', 'row': row})",
    "    for row_key, row in edited_by_key.items():",
    "        original_row = original_by_key.get(row_key)",
    "        if original_row is None or _vdab_row_signature(row, column_names) != _vdab_row_signature(original_row, column_names):",
    "            changes.append({'operation': 'upsert', 'row': row})",
    "    if len(changes) > 500:",
    "        raise RuntimeError('Save no more than 500 changed rows at a time.')",
    "    return changes",
    "",
    "def _vdab_rows_by_key(rows: list[dict[str, object]], primary_key: str) -> dict[str, dict[str, object]]:",
    "    keyed_rows = {}",
    "    for row in rows:",
    "        key_value = _vdab_sql_text_value(row.get(primary_key))",
    "        if key_value is None:",
    "            raise RuntimeError('Primary key values must not be null.')",
    "        token = json.dumps([type(row.get(primary_key)).__name__, key_value], ensure_ascii=False)",
    "        if token in keyed_rows:",
    "            raise RuntimeError('Primary key values must be unique in the edited rows.')",
    "        keyed_rows[token] = row",
    "    return keyed_rows",
    "",
    "def _vdab_row_signature(row: dict[str, object], column_names: list[str]) -> str:",
    "    return json.dumps([_vdab_sql_text_value(row.get(name)) for name in column_names], ensure_ascii=False)",
    "",
  );
}

function appendDataWindowQuerySetup(lines: string[]): void {
  lines.push(
    "def _vdab_sql_query_df(catalog: str, schema: str, table: str, max_rows: int, primary_key: str | None = None, query_statement: str | None = None, warehouse_id_override: str | None = None, source_kind: str = 'unityCatalogTable', database: str | None = None, endpoint: str | None = None, resource_environment_variable: str | None = None) -> pd.DataFrame:",
    "    if source_kind == 'lakebaseAutoscaling':",
    "        if not isinstance(database, str) or not isinstance(endpoint, str):",
    "            raise RuntimeError('The Lakebase database and endpoint must be selected before previewing.')",
    "        return _vdab_lakebase_query_df(schema, table, max_rows, query_statement, database, endpoint, resource_environment_variable)",
    "    if source_kind != 'unityCatalogTable':",
    "        raise RuntimeError('The selected database source is not supported by this generated app.')",
    "    warehouse_id = warehouse_id_override or os.environ.get('DATABRICKS_SQL_WAREHOUSE_ID', '')",
    "    if not re.fullmatch(r'[A-Za-z0-9_-]{1,128}', warehouse_id):",
    "        raise RuntimeError('Bind an existing SQL warehouse to this app before loading this table.')",
    "    if not isinstance(max_rows, int) or max_rows < 0 or max_rows > _VDAB_SQL_MAX_RESULT_ROWS:",
    "        raise RuntimeError('The requested SQL result row limit is invalid.')",
    "    table_reference = '.'.join(_vdab_quote_sql_identifier(name) for name in (catalog, schema, table))",
    "    if query_statement is not None:",
    "        statement = query_statement.strip()",
    "        if not statement.upper().startswith('SELECT '):",
    "            raise RuntimeError('The generated SQL query is invalid.')",
    "    elif primary_key is None:",
    "        statement = f'SELECT * FROM {table_reference}'",
    "    else:",
    "        key_column = _vdab_quote_sql_identifier(primary_key)",
    "        statement = f'SELECT COUNT(*) AS total_rows, COUNT({key_column}) AS non_null_rows, COUNT(DISTINCT {key_column}) AS unique_rows FROM {table_reference}'",
    "    if max_rows > 0:",
    "        statement += f' LIMIT {max_rows:d}'",
    "    request_body = {",
    "        'statement': statement,",
    "        'warehouse_id': warehouse_id,",
    "        'wait_timeout': '30s',",
    "        'on_wait_timeout': 'CONTINUE',",
    "        'disposition': 'INLINE',",
    "        'format': 'JSON_ARRAY',",
    "    }",
    "    request_body['row_limit'] = max_rows if max_rows > 0 else _VDAB_SQL_MAX_RESULT_ROWS",
    "    request_body['byte_limit'] = _VDAB_SQL_MAX_RESULT_BYTES",
    "    response_body, result_bytes = _vdab_sql_request('POST', '/api/2.0/sql/statements', request_body)",
    "    statement_id = response_body.get('statement_id')",
    "    if not isinstance(statement_id, str) or not re.fullmatch(r'[A-Za-z0-9-]{1,128}', statement_id):",
    "        raise RuntimeError('Databricks returned an invalid SQL statement identifier.')",
    "    status_part = response_body.get('status')",
    "    if not isinstance(status_part, dict):",
    "        raise RuntimeError('Databricks returned an invalid SQL statement status.')",
    "    state = status_part.get('state')",
    "    for _poll_attempt in range(12):",
    "        if state == 'SUCCEEDED':",
    "            break",
    "        if state not in ('PENDING', 'RUNNING'):",
    "            raise RuntimeError('The Databricks SQL statement did not complete successfully.')",
    "        time.sleep(1)",
    "        statement_path = '/api/2.0/sql/statements/' + urllib.parse.quote(statement_id, safe='')",
    "        statement_path += '?warehouse_id=' + urllib.parse.quote(warehouse_id, safe='')",
    "        response_body, response_bytes = _vdab_sql_request('GET', statement_path)",
    "        result_bytes += response_bytes",
    "        if result_bytes > _VDAB_SQL_MAX_RESULT_BYTES:",
    "            raise RuntimeError('The Databricks SQL result is too large to load safely.')",
    "        status_part = response_body.get('status')",
    "        if not isinstance(status_part, dict):",
    "            raise RuntimeError('Databricks returned an invalid SQL statement status.')",
    "        state = status_part.get('state')",
    "    if state != 'SUCCEEDED':",
    "        raise RuntimeError('The Databricks SQL statement timed out before results were ready.')",
  );
}

function appendDataWindowQueryResults(lines: string[]): void {
  lines.push(
    "    _vdab_sql_reject_truncated_result(response_body)",
    "    manifest = response_body.get('manifest')",
    "    if not isinstance(manifest, dict):",
    "        raise RuntimeError('Databricks returned an invalid SQL result manifest.')",
    "    schema_part = manifest.get('schema')",
    "    if not isinstance(schema_part, dict) or not isinstance(schema_part.get('columns'), list):",
    "        raise RuntimeError('Databricks returned invalid SQL column metadata.')",
    "    column_names = [column.get('name') for column in schema_part['columns'] if isinstance(column, dict)]",
    "    if len(column_names) != len(schema_part['columns']) or not all(isinstance(name, str) for name in column_names):",
    "        raise RuntimeError('Databricks returned invalid SQL column metadata.')",
    "    result_part = _vdab_sql_result_part(response_body)",
    "    if result_bytes > _VDAB_SQL_MAX_RESULT_BYTES:",
    "        raise RuntimeError('The Databricks SQL result is too large to load safely.')",
    "    rows = []",
    "    row_limit = max_rows if max_rows > 0 else _VDAB_SQL_MAX_RESULT_ROWS",
    "    next_chunk_index = 0",
    "    for _chunk_attempt in range(_VDAB_SQL_MAX_RESULT_CHUNKS):",
    "        data_array = result_part.get('data_array')",
    "        if not isinstance(data_array, list) or not all(isinstance(row, list) for row in data_array):",
    "            raise RuntimeError('Databricks returned invalid SQL row data.')",
    "        if len(rows) + len(data_array) > row_limit:",
    "            raise RuntimeError('The Databricks SQL result exceeded its configured row limit.')",
    "        rows.extend(data_array)",
    "        next_chunk_index = result_part.get('next_chunk_index')",
    "        if next_chunk_index is None:",
    "            break",
    "        if not isinstance(next_chunk_index, int) or next_chunk_index < 0:",
    "            raise RuntimeError('Databricks returned an invalid SQL result page.')",
    "        chunk_path = '/api/2.0/sql/statements/' + urllib.parse.quote(statement_id, safe='')",
    "        chunk_path += '/result/chunks/' + str(next_chunk_index) + '?warehouse_id=' + urllib.parse.quote(warehouse_id, safe='')",
    "        chunk_response, chunk_response_bytes = _vdab_sql_request('GET', chunk_path)",
    "        _vdab_sql_reject_truncated_result(chunk_response)",
    "        result_bytes += chunk_response_bytes",
    "        if result_bytes > _VDAB_SQL_MAX_RESULT_BYTES:",
    "            raise RuntimeError('The Databricks SQL result is too large to load safely.')",
    "        result_part = _vdab_sql_result_part(chunk_response)",
    "    else:",
    "        raise RuntimeError('The Databricks SQL result contains too many pages to load safely.')",
    "    return pd.DataFrame(rows, columns=column_names)",
  );
}

function appendPrimaryKeyValidationHelper(lines: string[]): void {
  lines.push(
    "",
    "def _vdab_sql_validate_primary_key(catalog: str, schema: str, table: str, primary_key: str) -> None:",
    "    statistics = _vdab_sql_query_df(catalog, schema, table, 1, primary_key)",
    "    if len(statistics) != 1:",
    "        raise RuntimeError('Databricks returned invalid primary key statistics.')",
    "    try:",
    "        total_rows = int(statistics.iloc[0]['total_rows'])",
    "        non_null_rows = int(statistics.iloc[0]['non_null_rows'])",
    "        unique_rows = int(statistics.iloc[0]['unique_rows'])",
    "    except (IndexError, KeyError, TypeError, ValueError, OverflowError):",
    "        raise RuntimeError('Databricks returned invalid primary key statistics.') from None",
    "    if total_rows != non_null_rows or total_rows != unique_rows:",
    "        raise RuntimeError('The selected primary key must be unique and non-null across the whole table before saving.')",
    "",
  );
}
