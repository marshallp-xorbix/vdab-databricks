import type { SaveTargetTableRef } from "../sharedReferences";

export type SaveToTableColumnOverrideReason =
  | "autogenerated"
  | "systemManaged"
  | "manualSkip";

export interface SaveToTableColumnMapping {
  formChildComponentCodeName: string;
  targetColumnName: string;
}

export interface SaveToTableColumnOverride {
  columnName: string;
  reason: SaveToTableColumnOverrideReason;
}

export interface SaveToTableParams {
  sourceFormComponentCodeName: string;
  targetTable: SaveTargetTableRef;
  excludedColumns: SaveToTableColumnOverride[];
  columnMappings: SaveToTableColumnMapping[];
}

export interface SaveToTableResult {
  saved: boolean;
}
