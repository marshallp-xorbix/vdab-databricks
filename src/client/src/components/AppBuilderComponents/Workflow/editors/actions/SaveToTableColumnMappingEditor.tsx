import type { FC } from "react";
import type {
  SaveToTableColumnOverrideReason,
  SaveToTableParams,
} from "../../../../../types/workflow";
import type { getSaveToTableSourceComponentOptions } from "../../../../../utils/workflow/actionReferenceOptions";
import { Label } from "../../../../ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "../../../../ui/select";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "../../../../ui/table";

const MAP_COLUMN_VALUE = "__map__";
const UNMAPPED_SOURCE_VALUE = "__unmapped__";

const COLUMN_OVERRIDE_OPTIONS: ReadonlyArray<{
  value: typeof MAP_COLUMN_VALUE | SaveToTableColumnOverrideReason;
  label: string;
}> = [
  { value: MAP_COLUMN_VALUE, label: "Map column" },
  { value: "autogenerated", label: "Autogenerated" },
  { value: "systemManaged", label: "System managed" },
  { value: "manualSkip", label: "Manual skip" },
];

type SaveToTableSourceOption = ReturnType<
  typeof getSaveToTableSourceComponentOptions
>[number];

interface ISaveToTableTargetColumn {
  name: string | undefined;
  type: string | undefined;
  nullable: boolean | undefined;
}

interface ISaveToTableColumnMappingEditorProps {
  params: SaveToTableParams;
  columns: ISaveToTableTargetColumn[];
  sourceOptions: SaveToTableSourceOption[];
  isLoading: boolean;
  errorMessage: string | null;
  onColumnModeChange: (
    columnName: string,
    mode: SaveToTableColumnOverrideReason | null,
  ) => void;
  onColumnMappingChange: (
    columnName: string,
    formChildComponentCodeName: string,
  ) => void;
}

/** Renders SaveToTable target columns and their source or exclusion mappings. */
const SaveToTableColumnMappingEditor: FC<
  Readonly<ISaveToTableColumnMappingEditorProps>
> = ({
  params,
  columns,
  sourceOptions,
  isLoading,
  errorMessage,
  onColumnModeChange,
  onColumnMappingChange,
}) => (
  <div className="space-y-3 rounded-md border border-border p-3">
    <div>
      <Label className="text-sm font-medium">Column Mapping</Label>
      <p className="text-xs text-muted-foreground">
        This phase only builds the strict mapping UI skeleton for SaveToTable.
      </p>
    </div>

    {isLoading && (
      <p className="text-xs text-muted-foreground">
        Loading target table columns...
      </p>
    )}
    {errorMessage && (
      <p className="text-xs text-destructive">{errorMessage}</p>
    )}
    {!isLoading && !errorMessage && columns.length === 0 && (
      <p className="text-xs text-muted-foreground">
        Select a target table to load available target columns.
      </p>
    )}

    {columns.length > 0 && (
      <Table>
        <TableHeader>
          <TableRow>
            <TableHead>Target Column</TableHead>
            <TableHead>Column Handling</TableHead>
            <TableHead>Source Form Field</TableHead>
            <TableHead>Metadata</TableHead>
          </TableRow>
        </TableHeader>
        <TableBody>
          {columns.map((column) => {
            const columnName = column.name ?? "";
            const exclusion = params.excludedColumns.find(
              (item) => item.columnName === columnName,
            );
            const mapping = params.columnMappings.find(
              (item) => item.targetColumnName === columnName,
            );
            const columnMode = exclusion?.reason ?? MAP_COLUMN_VALUE;

            return (
              <TableRow key={columnName}>
                <TableCell>
                  <div className="font-medium">{columnName}</div>
                  <div className="text-xs text-muted-foreground">
                    {column.type ?? "unknown"}
                  </div>
                </TableCell>
                <TableCell>
                  <Select
                    value={columnMode}
                    onValueChange={(value) =>
                      onColumnModeChange(
                        columnName,
                        value === MAP_COLUMN_VALUE
                          ? null
                          : (value as SaveToTableColumnOverrideReason),
                      )
                    }
                  >
                    <SelectTrigger
                      className="h-9 text-sm"
                      aria-label={`Column handling for ${columnName}`}
                    >
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      {COLUMN_OVERRIDE_OPTIONS.map((option) => (
                        <SelectItem key={option.value} value={option.value}>
                          {option.label}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </TableCell>
                <TableCell>
                  <Select
                    value={
                      mapping?.formChildComponentCodeName ??
                      UNMAPPED_SOURCE_VALUE
                    }
                    disabled={columnMode !== MAP_COLUMN_VALUE}
                    onValueChange={(value) =>
                      onColumnMappingChange(
                        columnName,
                        value === UNMAPPED_SOURCE_VALUE ? "" : value,
                      )
                    }
                  >
                    <SelectTrigger
                      className="h-9 text-sm"
                      aria-label={`Source form field for ${columnName}`}
                    >
                      <SelectValue placeholder="Select form field..." />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value={UNMAPPED_SOURCE_VALUE}>
                        Unmapped
                      </SelectItem>
                      {sourceOptions.map((option) => (
                        <SelectItem key={option.value} value={option.value}>
                          {option.label}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </TableCell>
                <TableCell className="text-xs text-muted-foreground">
                  {columnMode === MAP_COLUMN_VALUE
                    ? column.nullable === false
                      ? "Required"
                      : "Nullable"
                    : `Excluded: ${columnMode}`}
                </TableCell>
              </TableRow>
            );
          })}
        </TableBody>
      </Table>
    )}
  </div>
);

export default SaveToTableColumnMappingEditor;
