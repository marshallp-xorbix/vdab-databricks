using System.ComponentModel.DataAnnotations;
using Xorbix_Visual_Databricks_App_Builder.Models.DTOs.BuilderComponents;
using Xorbix_Visual_Databricks_App_Builder.Models.DTOs.Workflow;

namespace Xorbix_Visual_Databricks_App_Builder.Models
{
    /// <summary>
    /// Simple request for deployment from frontend (workspace URL comes from authenticated connection)
    /// </summary>
    public class SimpleDeployRequest
    {
        public string Description { get; init; } = "Generated by Xorbix Visual Databricks App Builder";
        public List<VdabComponentDto> FormComponents { get; init; } = new List<VdabComponentDto>();
        public WorkflowDefinitionDto WorkflowDefinition { get; init; } = new();
        public string DatabricksAppName { get; init; } = string.Empty;
        public int AppId { get; init; }
        public string TargetPath { get; init; } = string.Empty;
    }

    public class DeployAppFromFolderRequest
    {
        [Range(1, int.MaxValue, ErrorMessage = "Workspace connection ID is required.")]
        public int WorkspaceConnectionId { get; set; }
        public string WorkspaceUrl { get; set; } = string.Empty;
        public string AccessToken { get; set; } = string.Empty;
        public string DatabricksAppName { get; set; } = string.Empty;
        public string SourcePath { get; set; } = string.Empty;
    }

    public class DeployAppFromFolderResult
    {
        public bool Success { get; set; }
        public string AppId { get; set; } = string.Empty;
        public string DeploymentId { get; set; } = string.Empty;
        public string AppUrl { get; set; } = string.Empty;
        public string Message { get; set; } = string.Empty;
        public string? ErrorDetails { get; set; }
    }
}
