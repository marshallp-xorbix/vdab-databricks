/** Appends viewer-authorized, bounded Genie REST helpers to generated Python. */
export function appendGenieChatHelpers(lines: string[]): void {
  lines.push(
    "",
    "_VDAB_GENIE_MAX_HISTORY = 200",
    "_VDAB_GENIE_MAX_HISTORY_BYTES = 5000000",
    "_VDAB_GENIE_MAX_TEXT_LENGTH = 20000",
    "_VDAB_GENIE_MAX_RESULT_ROWS = 500",
    "_VDAB_GENIE_MAX_RESULT_BYTES = 200000",
    "_VDAB_GENIE_MAX_ATTACHMENTS = 20",
    "_VDAB_GENIE_MAX_RESPONSE_BYTES = 5000000",
    "_VDAB_GENIE_MAX_PROMPT_LENGTH = 10000",
    "_VDAB_GENIE_POLL_INTERVAL_SECONDS = 2",
    "_VDAB_GENIE_MAX_POLL_INTERVAL_SECONDS = 30",
    "_VDAB_GENIE_POLL_WINDOW_SECONDS = 30",
    "_VDAB_GENIE_MAX_WAIT_SECONDS = 600",
    "_VDAB_GENIE_ID_PATTERN = re.compile(r'^(?:[A-Fa-f0-9]{32}|[A-Fa-f0-9]{8}-(?:[A-Fa-f0-9]{4}-){3}[A-Fa-f0-9]{12})$')",
    "class _VDABGenieNoRedirectHandler(urllib.request.HTTPRedirectHandler):",
    "    def redirect_request(self, request: urllib.request.Request, file_pointer: object, status_code: int, message: str, headers: object, new_url: str) -> urllib.request.Request | None:",
    "        return None",
    "",
    "_VDAB_GENIE_OPENER = urllib.request.build_opener(_VDABGenieNoRedirectHandler())",
    "",
    "def _vdab_genie_request(method: str, path: str, body: dict[str, object] | None = None) -> dict[str, object]:",
    "    user_token = st.context.headers.get('x-forwarded-access-token')",
    "    if not user_token:",
    "        raise RuntimeError('The current viewer must grant this app the Genie user authorization scope.')",
    "    workspace_host = os.environ.get('DATABRICKS_HOST', '')",
    "    parsed_host = urllib.parse.urlsplit(workspace_host)",
    "    if parsed_host.scheme != 'https' or not parsed_host.hostname or parsed_host.username or parsed_host.password or parsed_host.path not in ('', '/') or parsed_host.query or parsed_host.fragment:",
    "        raise RuntimeError('The Databricks workspace host is not configured safely.')",
    "    if not path.startswith('/api/2.0/genie/'):",
    "        raise RuntimeError('The Genie request path is invalid.')",
    "    request_body = None if body is None else json.dumps(body).encode('utf-8')",
    "    request = urllib.request.Request(",
    "        f'{parsed_host.scheme}://{parsed_host.netloc}{path}',",
    "        data=request_body,",
    "        headers={'Authorization': f'Bearer {user_token}', 'Accept': 'application/json', 'Content-Type': 'application/json'},",
    "        method=method,",
    "    )",
    "    try:",
    "        with _VDAB_GENIE_OPENER.open(request, timeout=20) as response:",
    "            response_bytes = response.read(_VDAB_GENIE_MAX_RESPONSE_BYTES + 1)",
    "        if len(response_bytes) > _VDAB_GENIE_MAX_RESPONSE_BYTES:",
    "            raise RuntimeError('The Genie response exceeds the safe display limit.')",
    "        response_payload = json.loads(response_bytes.decode('utf-8'))",
    "    except urllib.error.HTTPError as error:",
    "        if error.code in (401, 403):",
    "            raise RuntimeError('Genie access was denied. Confirm the app genie scope, viewer consent, Genie space access, and data permissions.') from None",
    "        if error.code == 404:",
    "            raise RuntimeError('The selected Genie space or conversation is no longer available to this viewer.') from None",
    "        if error.code == 429:",
    "            raise RuntimeError('Genie is receiving too many requests. Wait briefly and try again.') from None",
    "        raise RuntimeError(f'Databricks rejected the Genie request (HTTP {error.code}).') from None",
    "    except TimeoutError:",
    "        raise RuntimeError('The Genie request timed out. Check the conversation status and try again.') from None",
    "    except urllib.error.URLError as error:",
    "        if isinstance(error.reason, TimeoutError):",
    "            raise RuntimeError('The Genie request timed out. Check the conversation status and try again.') from None",
    "        raise RuntimeError('The Databricks Genie API could not be reached.') from None",
    "    except (UnicodeDecodeError, json.JSONDecodeError):",
    "        raise RuntimeError('Databricks returned an invalid Genie response.') from None",
    "    if not isinstance(response_payload, dict):",
    "        raise RuntimeError('Databricks returned an invalid Genie response.')",
    "    return response_payload",
    "",
    "def _vdab_genie_read_id(value: object) -> str:",
    "    if not isinstance(value, str) or not _VDAB_GENIE_ID_PATTERN.fullmatch(value):",
    "        raise RuntimeError('Databricks returned an invalid Genie conversation identifier.')",
    "    return value",
    "",
    "def _vdab_genie_message_payload(response_payload: dict[str, object]) -> dict[str, object]:",
    "    message = response_payload.get('message', response_payload)",
    "    if not isinstance(message, dict):",
    "        raise RuntimeError('Databricks returned an invalid Genie message.')",
    "    return message",
    "",
    "def _vdab_genie_send(space_id: str, conversation_id: str | None, prompt: str) -> tuple[str, str, dict[str, object]]:",
    "    if not isinstance(prompt, str) or not prompt.strip() or len(prompt) > _VDAB_GENIE_MAX_PROMPT_LENGTH:",
    "        raise RuntimeError('Enter a Genie question with at most 10,000 characters.')",
    "    safe_space_id = _vdab_genie_read_id(space_id)",
    "    if conversation_id:",
    "        safe_conversation_id = _vdab_genie_read_id(conversation_id)",
    "        path = f'/api/2.0/genie/spaces/{urllib.parse.quote(safe_space_id, safe=\"\")}/conversations/{urllib.parse.quote(safe_conversation_id, safe=\"\")}/messages'",
    "        response_payload = _vdab_genie_request('POST', path, {'content': prompt})",
    "    else:",
    "        path = f'/api/2.0/genie/spaces/{urllib.parse.quote(safe_space_id, safe=\"\")}/start-conversation'",
    "        response_payload = _vdab_genie_request('POST', path, {'content': prompt})",
    "    message = _vdab_genie_message_payload(response_payload)",
    "    response_conversation_id = message.get('conversation_id', response_payload.get('conversation_id'))",
    "    response_message_id = message.get('message_id', message.get('id', response_payload.get('message_id'))) ",
    "    return (_vdab_genie_read_id(response_conversation_id), _vdab_genie_read_id(response_message_id), message)",
    "",
    "def _vdab_genie_poll(space_id: str, conversation_id: str, message_id: str, wait_seconds: float) -> dict[str, object] | None:",
    "    safe_space_id = _vdab_genie_read_id(space_id)",
    "    safe_conversation_id = _vdab_genie_read_id(conversation_id)",
    "    safe_message_id = _vdab_genie_read_id(message_id)",
    "    path = f'/api/2.0/genie/spaces/{urllib.parse.quote(safe_space_id, safe=\"\")}/conversations/{urllib.parse.quote(safe_conversation_id, safe=\"\")}/messages/{urllib.parse.quote(safe_message_id, safe=\"\")}'",
    "    deadline = time.monotonic() + max(0, wait_seconds)",
    "    poll_interval = _VDAB_GENIE_POLL_INTERVAL_SECONDS",
    "    while True:",
    "        message = _vdab_genie_message_payload(_vdab_genie_request('GET', path))",
    "        state = message.get('status')",
    "        if state in ('COMPLETED', 'FAILED', 'CANCELLED', 'QUERY_RESULT_EXPIRED'):",
    "            return message",
    "        remaining = deadline - time.monotonic()",
    "        if remaining <= 0:",
    "            return None",
    "        time.sleep(min(poll_interval, remaining))",
    "        poll_interval = min(poll_interval * 2, _VDAB_GENIE_MAX_POLL_INTERVAL_SECONDS)",
    "",
    "def _vdab_genie_read_query_result(space_id: str, conversation_id: str, message_id: str, attachment_id: str) -> dict[str, object] | None:",
    "    safe_space_id = _vdab_genie_read_id(space_id)",
    "    safe_conversation_id = _vdab_genie_read_id(conversation_id)",
    "    safe_message_id = _vdab_genie_read_id(message_id)",
    "    safe_attachment_id = _vdab_genie_read_id(attachment_id)",
    "    path = f'/api/2.0/genie/spaces/{urllib.parse.quote(safe_space_id, safe=\"\")}/conversations/{urllib.parse.quote(safe_conversation_id, safe=\"\")}/messages/{urllib.parse.quote(safe_message_id, safe=\"\")}/attachments/{urllib.parse.quote(safe_attachment_id, safe=\"\")}/query-result'",
    "    response_payload = _vdab_genie_request('GET', path)",
    "    statement_response = response_payload.get('statement_response')",
    "    if not isinstance(statement_response, dict):",
    "        return None",
    "    manifest = statement_response.get('manifest')",
    "    result = statement_response.get('result')",
    "    if not isinstance(manifest, dict) or not isinstance(result, dict):",
    "        return None",
    "    schema = manifest.get('schema')",
    "    columns = schema.get('columns') if isinstance(schema, dict) else None",
    "    rows = result.get('data_array')",
    "    if not isinstance(columns, list) or not isinstance(rows, list):",
    "        return None",
    "    column_names = [column.get('name')[:_VDAB_GENIE_MAX_TEXT_LENGTH] for column in columns if isinstance(column, dict) and isinstance(column.get('name'), str)]",
    "    if len(column_names) != len(columns) or len(column_names) > 100:",
    "        return None",
    "    safe_rows = []",
    "    result_bytes = 0",
    "    for row in rows[:_VDAB_GENIE_MAX_RESULT_ROWS]:",
    "        if not isinstance(row, list) or len(row) != len(column_names) or any(value is not None and not isinstance(value, (str, int, float, bool)) for value in row):",
    "            return None",
    "        safe_row = [value[:_VDAB_GENIE_MAX_TEXT_LENGTH] if isinstance(value, str) else value for value in row]",
    "        row_bytes = len(json.dumps(safe_row, ensure_ascii=False).encode('utf-8'))",
    "        if result_bytes + row_bytes > _VDAB_GENIE_MAX_RESULT_BYTES:",
    "            break",
    "        safe_rows.append(safe_row)",
    "        result_bytes += row_bytes",
    "    return {'columns': column_names, 'rows': safe_rows, 'truncated': len(rows) > len(safe_rows) or result.get('next_chunk_index') is not None}",
    "",
    "def _vdab_genie_assistant_parts(space_id: str, conversation_id: str, message_id: str, message: dict[str, object]) -> list[dict[str, object]]:",
    "    attachments = message.get('attachments')",
    "    if not isinstance(attachments, list):",
    "        return [{'kind': 'markdown', 'body': '_(No response content.)_'}]",
    "    parts = []",
    "    for attachment in attachments[:_VDAB_GENIE_MAX_ATTACHMENTS]:",
    "        if not isinstance(attachment, dict):",
    "            continue",
    "        text_attachment = attachment.get('text')",
    "        if isinstance(text_attachment, dict) and isinstance(text_attachment.get('content'), str) and text_attachment['content']:",
    "            parts.append({'kind': 'markdown', 'body': text_attachment['content'][:_VDAB_GENIE_MAX_TEXT_LENGTH]})",
    "        query_attachment = attachment.get('query')",
    "        if isinstance(query_attachment, dict):",
    "            sql_text = query_attachment.get('query')",
    "            sql_text = sql_text[:_VDAB_GENIE_MAX_TEXT_LENGTH] if isinstance(sql_text, str) else ''",
    "            query_title = query_attachment.get('description') or query_attachment.get('title') or 'Genie query'",
    "            query_title = query_title[:_VDAB_GENIE_MAX_TEXT_LENGTH] if isinstance(query_title, str) else 'Genie query'",
    "            query_part = {'kind': 'sql', 'title': query_title, 'code': sql_text, 'result': None}",
    "            attachment_id = attachment.get('attachment_id')",
    "            if isinstance(attachment_id, str) and _VDAB_GENIE_ID_PATTERN.fullmatch(attachment_id):",
    "                try:",
    "                    query_part['result'] = _vdab_genie_read_query_result(space_id, conversation_id, message_id, attachment_id)",
    "                except RuntimeError as error:",
    "                    query_part['result_error'] = str(error)",
    "            parts.append(query_part)",
    "    if len(attachments) > _VDAB_GENIE_MAX_ATTACHMENTS:",
    "        parts.append({'kind': 'markdown', 'body': 'Additional Genie response attachments were omitted to keep this chat bounded.'})",
    "    return parts or [{'kind': 'markdown', 'body': '_(No response content.)_'}]",
    "",
    "def _vdab_genie_render_history_entry(message: dict[str, object]) -> None:",
    "    role = message.get('role')",
    "    if role not in ('user', 'assistant'):",
    "        return",
    "    with st.chat_message(role):",
    "        if role == 'user':",
    "            st.markdown(message.get('text', ''))",
    "            return",
    "        parts = message.get('parts', [])",
    "        if not isinstance(parts, list):",
    "            return",
    "        for part in parts:",
    "            if not isinstance(part, dict):",
    "                continue",
    "            if part.get('kind') == 'markdown':",
    "                st.markdown(part.get('body') or '')",
    "            elif part.get('kind') == 'sql':",
    "                st.markdown(part.get('title') or 'Genie query')",
    "                with st.expander('Generated SQL'):",
    "                    st.code(part.get('code') or '', language='sql')",
    "                result = part.get('result')",
    "                if isinstance(result, dict) and isinstance(result.get('columns'), list) and isinstance(result.get('rows'), list):",
    "                    st.dataframe(pd.DataFrame(result['rows'], columns=result['columns']), use_container_width=True)",
    "                    if result.get('truncated'):",
    "                        st.caption('The Genie result is larger than this chat display limit. Showing a bounded preview.')",
    "                elif isinstance(part.get('result_error'), str):",
    "                    st.caption(part['result_error'])",
    "                else:",
    "                    st.caption('Genie did not return a query result for this message.')",
    "",
    "def _vdab_genie_trim_history(history: list[dict[str, object]]) -> bool:",
    "    was_trimmed = False",
    "    while len(history) > _VDAB_GENIE_MAX_HISTORY:",
    "        history.pop(0)",
    "        was_trimmed = True",
    "    while history and len(json.dumps(history, ensure_ascii=False).encode('utf-8')) > _VDAB_GENIE_MAX_HISTORY_BYTES:",
    "        history.pop(0)",
    "        was_trimmed = True",
    "    return was_trimmed",
    "",
    "def _vdab_genie_append_assistant(history: list[dict[str, object]], space_id: str, conversation_id: str, message_id: str, message: dict[str, object]) -> bool:",
    "    status = message.get('status')",
    "    if status == 'FAILED':",
    "        body = 'Genie could not complete this question. Check the selected space and its data permissions, then try again.'",
    "        parts = [{'kind': 'markdown', 'body': body}]",
    "    elif status == 'CANCELLED':",
    "        parts = [{'kind': 'markdown', 'body': 'This Genie response was cancelled.'}]",
    "    elif status == 'QUERY_RESULT_EXPIRED':",
    "        parts = [{'kind': 'markdown', 'body': 'This Genie query result expired. Ask the question again to run it again.'}]",
    "    else:",
    "        parts = _vdab_genie_assistant_parts(space_id, conversation_id, message_id, message)",
    "    history.append({'role': 'assistant', 'parts': parts})",
    "    return _vdab_genie_trim_history(history)",
    "",
    "def _vdab_genie_render_chat_body(state_key: str, space_id: str, total_height_pixels: int) -> None:",
    "    history_key = f'vdab_genie_history_{state_key}'",
    "    conversation_key = f'vdab_genie_conversation_{state_key}'",
    "    pending_key = f'vdab_genie_pending_{state_key}'",
    "    history_trimmed_key = f'vdab_genie_history_trimmed_{state_key}'",
    "    history = st.session_state.setdefault(history_key, [])",
    "    if not isinstance(history, list):",
    "        history = []",
    "        st.session_state[history_key] = history",
    "    if st.session_state.get(history_trimmed_key):",
    "        st.caption('Older Genie messages were removed to keep the chat history within its display limit.')",
    "    message_height = max(180, total_height_pixels - 105)",
    "    with st.container(height=message_height, border=False):",
    "        for history_message in history[-_VDAB_GENIE_MAX_HISTORY:]:",
    "            if isinstance(history_message, dict):",
    "                _vdab_genie_render_history_entry(history_message)",
    "    pending = st.session_state.get(pending_key)",
    "    if isinstance(pending, dict):",
    "        st.info('Genie is still processing this question.')",
    "        if st.button('Check Genie response', key=f'vdab_genie_check_{state_key}'):",
    "            conversation_id = st.session_state.get(conversation_key)",
    "            message_id = pending.get('message_id')",
    "            started_at = pending.get('started_at')",
    "            if not isinstance(started_at, (int, float)):",
    "                started_at = time.time()",
    "            remaining_total = _VDAB_GENIE_MAX_WAIT_SECONDS - (time.time() - started_at)",
    "            if remaining_total <= 0:",
    "                history.append({'role': 'assistant', 'parts': [{'kind': 'markdown', 'body': 'Genie did not finish within ten minutes. Ask again or check the query in Databricks.'}]})",
    "                st.session_state[pending_key] = None",
    "            else:",
    "                try:",
    "                    safe_conversation_id = _vdab_genie_read_id(conversation_id)",
    "                    safe_message_id = _vdab_genie_read_id(message_id)",
    "                    with st.spinner('Checking Genie response…'):",
    "                        completed_message = _vdab_genie_poll(space_id, safe_conversation_id, safe_message_id, min(_VDAB_GENIE_POLL_WINDOW_SECONDS, remaining_total))",
    "                    if completed_message is None:",
    "                        st.caption('Genie is still working. Check again to continue waiting; polling stops after ten minutes.')",
    "                    else:",
    "                        if _vdab_genie_append_assistant(history, space_id, safe_conversation_id, safe_message_id, completed_message):",
    "                            st.session_state[history_trimmed_key] = True",
    "                        st.session_state[pending_key] = None",
    "                except RuntimeError as error:",
    "                    history.append({'role': 'assistant', 'parts': [{'kind': 'markdown', 'body': str(error)}]})",
    "                    st.session_state[pending_key] = None",
    "            if _vdab_genie_trim_history(history):",
    "                st.session_state[history_trimmed_key] = True",
    "            st.rerun()",
    "    else:",
    "        with st.container(border=False):",
    "            prompt = st.chat_input('Ask a question…', max_chars=_VDAB_GENIE_MAX_PROMPT_LENGTH, key=f'vdab_genie_input_{state_key}')",
    "        if prompt:",
    "            history.append({'role': 'user', 'text': prompt})",
    "            if _vdab_genie_trim_history(history):",
    "                st.session_state[history_trimmed_key] = True",
    "            started_at = time.time()",
    "            try:",
    "                current_conversation_id = st.session_state.get(conversation_key)",
    "                conversation_id, message_id, initial_message = _vdab_genie_send(space_id, current_conversation_id, prompt)",
    "                st.session_state[conversation_key] = conversation_id",
    "                state = initial_message.get('status')",
    "                if state in ('COMPLETED', 'FAILED', 'CANCELLED', 'QUERY_RESULT_EXPIRED'):",
    "                    if _vdab_genie_append_assistant(history, space_id, conversation_id, message_id, initial_message):",
    "                        st.session_state[history_trimmed_key] = True",
    "                else:",
    "                    st.session_state[pending_key] = {'message_id': message_id, 'started_at': started_at}",
    "                    with st.spinner('Genie is working…'):",
    "                        completed_message = _vdab_genie_poll(space_id, conversation_id, message_id, _VDAB_GENIE_POLL_WINDOW_SECONDS)",
    "                    if completed_message is not None:",
    "                        if _vdab_genie_append_assistant(history, space_id, conversation_id, message_id, completed_message):",
    "                            st.session_state[history_trimmed_key] = True",
    "                        st.session_state[pending_key] = None",
    "            except RuntimeError as error:",
    "                history.append({'role': 'assistant', 'parts': [{'kind': 'markdown', 'body': str(error)}]})",
    "                st.session_state[pending_key] = None",
    "                if _vdab_genie_trim_history(history):",
    "                    st.session_state[history_trimmed_key] = True",
    "            st.rerun()",
    "",
    "def _vdab_render_genie_chat(state_key: str, space_id: str, show_border: bool = False, total_height_pixels: int = 600) -> None:",
    "    if not isinstance(space_id, str) or not _VDAB_GENIE_ID_PATTERN.fullmatch(space_id):",
    "        st.error('The saved Genie space identifier is invalid. Select a Genie space in the builder and regenerate this app.')",
    "        return",
    "    with st.container(border=show_border):",
    "        _vdab_genie_render_chat_body(f'{state_key}_{space_id}', space_id, total_height_pixels)",
    "",
  );
}
