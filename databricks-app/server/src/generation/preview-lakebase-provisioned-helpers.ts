/** Adds viewer-authorized runtime helpers for existing Lakebase database resources. */
export function appendLakebaseProvisionedHelpers(lines: string[]): void {
  lines.push(
    "",
    "def _vdab_lakebase_provisioned_request(method: str, path: str, body: dict[str, object] | None = None) -> tuple[dict[str, object], int]:",
    "    try:",
    "        return _vdab_sql_request(method, path, body)",
    "    except RuntimeError:",
    "        raise RuntimeError('The current viewer could not access this Lakebase Provisioned instance. Check the postgres scope and workspace permissions.') from None",
    "",
    "def _vdab_lakebase_provisioned_connection_settings(database: str, instance_name: str, resource_environment_variable: str) -> dict[str, object]:",
    "    user_token = st.context.headers.get('x-forwarded-access-token')",
    "    user_email = st.context.headers.get('x-forwarded-email')",
    "    if not user_token or not user_email:",
    "        raise RuntimeError('The current viewer did not grant Lakebase user authorization.')",
    "    if not re.fullmatch(r'[^\\s@]+@[^\\s@]+', user_email) or len(user_email) > 320:",
    "        raise RuntimeError('Databricks did not provide a valid Lakebase user identity.')",
    "    if not re.fullmatch(r'[A-Za-z0-9_-]{1,128}', instance_name) or not re.fullmatch(r'[A-Za-z0-9_$-]{1,63}', database) or database.startswith('unresolved_'):",
    "        raise RuntimeError('The selected Lakebase Provisioned resource reference is invalid.')",
    "    instance_path = '/api/2.0/database/instances/' + urllib.parse.quote(instance_name, safe='')",
    "    instance, _response_bytes = _vdab_lakebase_provisioned_request('GET', instance_path)",
    "    instance_host = instance.get('read_write_dns')",
    "    host_pattern = r'ep-[a-z0-9-]+\\.database\\.[a-z0-9-]+\\.(?:(?:dev|cloud)\\.)?databricks\\.com|ep-[a-z0-9-]+\\.database\\.[a-z0-9-]+\\.(?:gcp\\.databricks\\.com|azuredatabricks\\.net)'",
    "    if not isinstance(instance_host, str) or not re.fullmatch(host_pattern, instance_host):",
    "        raise RuntimeError('Databricks returned an invalid Lakebase database host.')",
    "    if not re.fullmatch(r'VDAB_LAKEBASE_HOST_[A-F0-9]{16}', resource_environment_variable):",
    "        raise RuntimeError('The selected Lakebase App resource reference is invalid.')",
    "    host = os.environ.get(resource_environment_variable, '')",
    "    ssl_mode = os.environ.get('PGSSLMODE', '')",
    "    try:",
    "        port = int(os.environ.get('PGPORT', ''))",
    "    except ValueError:",
    "        raise RuntimeError('Lakebase connection settings are incomplete.') from None",
    "    if not isinstance(host, str) or host.lower() != instance_host.lower() or not 1 <= port <= 65535 or ssl_mode not in ('require', 'verify-ca', 'verify-full'):",
    "        raise RuntimeError('The selected Lakebase instance is not bound to this generated app.')",
    "    credential, _response_bytes = _vdab_lakebase_provisioned_request('POST', '/api/2.0/database/credentials', {'instance_names': [instance_name]})",
    "    token = credential.get('token')",
    "    expiry = credential.get('expiration_time')",
    "    if not isinstance(token, str) or not token or len(token) > 10000 or not isinstance(expiry, str) or not expiry:",
    "        raise RuntimeError('Databricks returned an invalid Lakebase credential.')",
    "    return {'host': host, 'port': port, 'user': user_email, 'password': token, 'database': database, 'ssl': ssl_mode, 'timeout': 30, 'command_timeout': 30, 'server_settings': {'default_transaction_read_only': 'on'}}",
    "",
    "async def _vdab_lakebase_provisioned_fetch_async(statement: str, database: str, instance_name: str, max_rows: int, resource_environment_variable: str):",
    "    if not isinstance(max_rows, int) or max_rows < 1 or max_rows > _VDAB_SQL_MAX_RESULT_ROWS:",
    "        raise RuntimeError('The requested Lakebase result row limit is invalid.')",
    "    bounded_statement = _vdab_postgres_sql(statement.strip().removesuffix(';').strip())",
    "    if not bounded_statement.upper().startswith(('SELECT ', 'WITH ')):",
    "        raise RuntimeError('Lakebase RunSql accepts read-only SELECT queries.')",
    "    wrapped_statement = 'SELECT * FROM (' + bounded_statement + ') AS _vdab_result LIMIT ' + str(max_rows + 1)",
    "    size_statement = 'SELECT pg_column_size(_vdab_result) FROM (' + bounded_statement + ') AS _vdab_result LIMIT ' + str(max_rows + 1)",
    "    settings = _vdab_lakebase_provisioned_connection_settings(database, instance_name, resource_environment_variable)",
    "    connection = None",
    "    try:",
    "        connection = await asyncpg.connect(**settings)",
    "        async with connection.transaction(isolation='repeatable_read', readonly=True):",
    "            row_count = 0",
    "            estimated_bytes = 0",
    "            async for row_size in connection.cursor(size_statement, prefetch=32):",
    "                row_count += 1",
    "                if row_count > max_rows:",
    "                    raise RuntimeError('The Lakebase SQL result exceeded its configured row limit.')",
    "                row_bytes = int(row_size[0] or 0)",
    "                if row_bytes > _VDAB_LAKEBASE_MAX_ROW_BYTES:",
    "                    raise RuntimeError('A Lakebase SQL row exceeds its configured size limit.')",
    "                estimated_bytes += row_bytes",
    "                if estimated_bytes > _VDAB_SQL_MAX_RESULT_BYTES:",
    "                    raise RuntimeError('The Lakebase SQL result is too large to load safely.')",
    "            records = []",
    "            serialized_bytes = 0",
    "            async for record in connection.cursor(wrapped_statement, prefetch=32):",
    "                serialized_bytes += len(json.dumps(dict(record), default=str, ensure_ascii=False, separators=(',', ':')).encode('utf-8'))",
    "                if serialized_bytes > _VDAB_SQL_MAX_RESULT_BYTES:",
    "                    raise RuntimeError('The Lakebase SQL result is too large to load safely.')",
    "                records.append(record)",
    "        return records",
    "    except asyncpg.PostgresError:",
    "        raise RuntimeError('Lakebase denied or rejected the current viewer query. Check the postgres scope and viewer role grants.') from None",
    "    except (asyncpg.exceptions.InterfaceError, OSError, TimeoutError):",
    "        raise RuntimeError('The Lakebase PostgreSQL endpoint could not be reached safely.') from None",
    "    finally:",
    "        if connection is not None:",
    "            await connection.close()",
    "",
    "def _vdab_lakebase_provisioned_query_df(schema: str, table: str, max_rows: int, query_statement: str | None = None, database: str = '', instance_name: str = '', resource_environment_variable: str = '') -> pd.DataFrame:",
    "    if query_statement is None:",
    "        if not schema or not table:",
    "            raise RuntimeError('The selected Lakebase table is incomplete.')",
    "        query_statement = 'SELECT * FROM ' + _vdab_postgres_sql(_vdab_quote_sql_identifier(schema)) + '.' + _vdab_postgres_sql(_vdab_quote_sql_identifier(table))",
    "    elif not isinstance(query_statement, str) or len(query_statement.encode('utf-8')) > 100000:",
    "        raise RuntimeError('The Lakebase SQL query is invalid or too large.')",
    "    effective_limit = _VDAB_SQL_MAX_RESULT_ROWS if max_rows == 0 else max_rows",
    "    try:",
    "        records = asyncio.run(_vdab_lakebase_provisioned_fetch_async(query_statement, database, instance_name, effective_limit, resource_environment_variable))",
    "    except RuntimeError:",
    "        raise",
    "    except Exception:",
    "        raise RuntimeError('Lakebase could not complete the current viewer query.') from None",
    "    if records:",
    "        return pd.DataFrame([dict(record) for record in records])",
    "    return pd.DataFrame()",
    "",
    "async def _vdab_lakebase_provisioned_execute_async(statement: str, values: list[object], database: str, instance_name: str, resource_environment_variable: str) -> int:",
    "    settings = _vdab_lakebase_provisioned_connection_settings(database, instance_name, resource_environment_variable)",
    "    settings['server_settings'] = {}",
    "    connection = None",
    "    try:",
    "        connection = await asyncpg.connect(**settings)",
    "        async with connection.transaction():",
    "            status = await connection.execute(statement, *values)",
    "        affected = status.rsplit(' ', 1)[-1]",
    "        if not affected.isdigit():",
    "            raise RuntimeError('Lakebase returned an invalid write result.')",
    "        return int(affected)",
    "    except asyncpg.PostgresError:",
    "        raise RuntimeError('Lakebase denied or rejected the current viewer write. Check the postgres scope and viewer role grants.') from None",
    "    except (asyncpg.exceptions.InterfaceError, OSError, TimeoutError):",
    "        raise RuntimeError('The Lakebase PostgreSQL endpoint could not be reached safely.') from None",
    "    finally:",
    "        if connection is not None:",
    "            await connection.close()",
    "",
    "def _vdab_lakebase_provisioned_execute(statement: str, values: list[object], database: str, instance_name: str, resource_environment_variable: str) -> int:",
    "    if len(statement.encode('utf-8')) > 100000 or len(values) > 500:",
    "        raise RuntimeError('The Lakebase write exceeds its configured query or value limit.')",
    "    try:",
    "        return asyncio.run(_vdab_lakebase_provisioned_execute_async(statement, values, database, instance_name, resource_environment_variable))",
    "    except RuntimeError:",
    "        raise",
    "    except Exception:",
    "        raise RuntimeError('Lakebase could not complete the current viewer write.') from None",
    "",
  );
}
