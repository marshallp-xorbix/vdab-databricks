function definition(
  id: string,
  codeName: string,
  type: ProjectComponentType,
  category: ComponentCategory,
  icon: string,
  props: ProjectJsonObject,
  supportedBindings: ComponentBindingType[] | null = null,
  supportedEvents: string[] | null = null,
  children: string[] | null = null,
): ComponentDefinition {
  return {
    id,
    codeName,
    type,
    category,
    icon,
    layout: null,
    schemaVersion: 1,
    bindings: null,
    supportedBindings,
    supportedEvents,
    children,
    props,
  };
}

function axis(scaleType: string, transform: string): ProjectJsonObject {
  return {
    field: null,
    displayName: null,
    scaleType,
    transform,
  };
}
