import { useEffect, useState, type FC } from "react";
import {
  databricksDataConnectorApi,
  type UnityCatalogTableDetails,
} from "../../../../../providers/DatabricksDataConnectorApi";
import {
  isWorkflowActionNode,
  type SaveToTableParams,
  type SaveToTableColumnOverrideReason,
} from "../../../../../types/workflow";
import {
  getSaveToTableSourceComponentOptions,
  getWorkflowTriggerComponent,
  isWorkflowTriggerForm,
} from "../../../../../utils/workflow/actionReferenceOptions";
import { LakebaseAutoscalingTableSelectorFields } from "../../../../properties/LakebaseAutoscalingTableSelectorFields";
import { LakebaseTableSelectorFields } from "../../../../properties/LakebaseTableSelectorFields";
import { UnityCatalogTableSelectorFields } from "../../../../properties/UnityCatalogTableSelectorFields";
import { Label } from "../../../../ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "../../../../ui/select";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "../../../../ui/table";
import type { WorkflowActionEditorProps } from "./types";
import { useLogger } from "../../../../../logger/useLogger";

const MAP_COLUMN_VALUE = "__map__";
const UNMAPPED_SOURCE_VALUE = "__unmapped__";

const COLUMN_OVERRIDE_OPTIONS: Array<{
  value: typeof MAP_COLUMN_VALUE | SaveToTableColumnOverrideReason;
  label: string;
}> = [
  { value: MAP_COLUMN_VALUE, label: "Map column" },
  { value: "autogenerated", label: "Autogenerated" },
  { value: "systemManaged", label: "System managed" },
  { value: "manualSkip", label: "Manual skip" },
];

export const SaveToTableEditor: FC<WorkflowActionEditorProps> = ({
  workflowId,
  workflow,
  node,
  components,
  workspaceConnectionId,
  onUpdateNode,
}) => {
  const logger = useLogger("SaveToTableEditor");
  const [tableDetails, setTableDetails] =
    useState<UnityCatalogTableDetails | null>(null);
  const [loadingColumns, setLoadingColumns] = useState(false);
  const [tableDetailsError, setTableDetailsError] = useState<string | null>(
    null,
  );

  const triggerComponent = getWorkflowTriggerComponent(workflow, components);
  const triggerIsForm = isWorkflowTriggerForm(workflow, components);
  const sourceOptions = getSaveToTableSourceComponentOptions(
    workflow,
    components,
  );
  const isSaveToTableNode = isWorkflowActionNode(node, "SaveToTable");
  const saveToTableParams = isSaveToTableNode ? node.params : null;
  const sourceFormComponentCodeName =
    saveToTableParams?.sourceFormComponentCodeName;
  const targetWorkspaceConnectionId =
    saveToTableParams?.targetTable.workspaceConnectionId;
  const targetTableType = saveToTableParams?.targetTable.tableType;
  const targetCatalog = saveToTableParams?.targetTable.catalog;
  const targetSchema = saveToTableParams?.targetTable.schema;
  const targetTableName = saveToTableParams?.targetTable.table;

  useEffect(() => {
    if (!triggerIsForm || !triggerComponent?.codeName) {
      return;
    }

    if (!isSaveToTableNode) {
      return;
    }

    const needsSourceSync =
      sourceFormComponentCodeName !== triggerComponent.codeName;
    const needsWorkspaceSync =
      workspaceConnectionId != null &&
      targetWorkspaceConnectionId !== workspaceConnectionId;

    if (!needsSourceSync && !needsWorkspaceSync) {
      return;
    }

    onUpdateNode(workflowId, node.id, (current) =>
      isWorkflowActionNode(current, "SaveToTable")
        ? {
            ...current,
            params: {
              ...current.params,
              sourceFormComponentCodeName: triggerComponent.codeName,
              targetTable: {
                ...current.params.targetTable,
                workspaceConnectionId:
                  workspaceConnectionId ??
                  current.params.targetTable.workspaceConnectionId,
              },
            },
          }
        : current,
    );
  }, [
    onUpdateNode,
    node.id,
    sourceFormComponentCodeName,
    targetWorkspaceConnectionId,
    triggerComponent,
    triggerIsForm,
    isSaveToTableNode,
    workflowId,
    workspaceConnectionId,
  ]);

  useEffect(() => {
    let active = true;

    if (!isSaveToTableNode) {
      return;
    }

    const fetchTableDetails = async () => {
      if (
        (targetTableType !== "unityCatalogTable" && targetTableType !== "lakebaseProvisionedDatabase") ||
        !workspaceConnectionId ||
        workspaceConnectionId <= 0 ||
        !targetCatalog ||
        !targetSchema ||
        !targetTableName
      ) {
        if (active) {
          setTableDetails(null);
          setTableDetailsError(null);
        }
        return;
      }

      setLoadingColumns(true);
      setTableDetailsError(null);

      try {
        const details =
          await databricksDataConnectorApi.getUnityCatalogTableDetails(
            workspaceConnectionId,
            targetCatalog,
            targetSchema,
            targetTableName,
          );

        if (active) {
          setTableDetails(details);
        }
      } catch (err) {
        if (active) {
          logger.UI.error(
            "[SaveToTableEditor] Failed to fetch target table metadata:",
            err,
          );
          setTableDetails(null);
          setTableDetailsError(
            err instanceof Error
              ? err.message
              : "Failed to load table metadata",
          );
        }
      } finally {
        if (active) {
          setLoadingColumns(false);
        }
      }
    };

    void fetchTableDetails();

    return () => {
      active = false;
    };
  }, [
    isSaveToTableNode,
    targetCatalog,
    targetSchema,
    targetTableName,
    targetTableType,
    workspaceConnectionId,
  ]);

  if (!saveToTableParams) {
    return null;
  }

  const targetTable = saveToTableParams.targetTable;
  const targetColumns = tableDetails?.columns ?? [];

  const updateTargetTable = (
    updater: (
      current: SaveToTableParams["targetTable"],
    ) => SaveToTableParams["targetTable"],
  ) => {
    onUpdateNode(workflowId, node.id, (current) =>
      isWorkflowActionNode(current, "SaveToTable")
        ? {
            ...current,
            params: {
              ...current.params,
              targetTable: updater(current.params.targetTable),
            },
          }
        : current,
    );
  };

  const updateColumnMode = (
    columnName: string,
    mode: typeof MAP_COLUMN_VALUE | SaveToTableColumnOverrideReason,
  ) => {
    onUpdateNode(workflowId, node.id, (current) => {
      if (!isWorkflowActionNode(current, "SaveToTable")) {
        return current;
      }

      const nextMappings = current.params.columnMappings.filter(
        (mapping) => mapping.targetColumnName !== columnName,
      );
      const nextExcludedColumns = current.params.excludedColumns.filter(
        (column) => column.columnName !== columnName,
      );

      return {
        ...current,
        params: {
          ...current.params,
          columnMappings: nextMappings,
          excludedColumns:
            mode === MAP_COLUMN_VALUE
              ? nextExcludedColumns
              : [
                  ...nextExcludedColumns,
                  {
                    columnName,
                    reason: mode,
                  },
                ],
        },
      };
    });
  };

  const updateColumnMapping = (
    columnName: string,
    formChildComponentCodeName: string,
  ) => {
    onUpdateNode(workflowId, node.id, (current) => {
      if (!isWorkflowActionNode(current, "SaveToTable")) {
        return current;
      }

      const nextExcludedColumns = current.params.excludedColumns.filter(
        (column) => column.columnName !== columnName,
      );
      const nextMappings = current.params.columnMappings.filter(
        (mapping) => mapping.targetColumnName !== columnName,
      );

      return {
        ...current,
        params: {
          ...current.params,
          excludedColumns: nextExcludedColumns,
          columnMappings:
            formChildComponentCodeName === ""
              ? nextMappings
              : [
                  ...nextMappings,
                  {
                    targetColumnName: columnName,
                    formChildComponentCodeName,
                  },
                ],
        },
      };
    });
  };

  if (!triggerIsForm || !triggerComponent?.codeName) {
    return (
      <div className="mt-2 rounded-md border border-warning/30 bg-warning-subtle px-3 py-2 text-sm text-warning-foreground">
        SaveToTable is only available when the workflow trigger component is a
        form.
      </div>
    );
  }

  return (
    <div className="mt-2 space-y-4">
      <div className="rounded-md border border-border p-3 space-y-3">
        <div className="grid gap-3 md:grid-cols-2">
          <div className="space-y-1">
            <Label className="text-sm">Source Form</Label>
            <div className="flex h-9 items-center rounded-md border border-border bg-muted px-3 text-sm text-foreground">
              {triggerComponent.codeName}
            </div>
            <p className="text-xs text-muted-foreground">
              SaveToTable always uses the workflow trigger form as its source.
            </p>
          </div>

          <div className="space-y-1">
            <Label className="text-sm">Available Fields</Label>
            {sourceOptions.length === 0 ? (
              <p className="rounded-md border border-dashed border-border px-3 py-2 text-xs text-muted-foreground">
                No supported form field descendants were found under the trigger
                form.
              </p>
            ) : (
              <p className="rounded-md border border-dashed border-border px-3 py-2 text-xs text-muted-foreground">
                {sourceOptions.map((option) => option.label).join(", ")}
              </p>
            )}
          </div>
        </div>
      </div>

      <div className="rounded-md border border-border p-3 space-y-3">
        <div className="grid gap-3 lg:grid-cols-[minmax(0,220px)_1fr] lg:items-start">
          <div className="space-y-1">
            <Label className="text-sm font-medium">Target Type</Label>
            <Select
              value={targetTable.tableType}
              onValueChange={(value) => {
                const wc = workspaceConnectionId ?? 0;
                updateTargetTable(() => {
                  if (value === "lakebaseProvisionedDatabase") {
                    return {
                      tableType: "lakebaseProvisionedDatabase",
                      workspaceConnectionId: wc,
                      instanceName: "",
                      database: "",
                      catalog: "",
                      schema: "",
                      table: "",
                    };
                  }
                  if (value === "lakebaseAutoscaling") {
                    return {
                      tableType: "lakebaseAutoscaling",
                      workspaceConnectionId: wc,
                      projectId: "",
                      branchId: "",
                      endpointId: "",
                      database: "",
                      catalog: "",
                      schema: "",
                      table: "",
                    };
                  }
                  return {
                    tableType: "unityCatalogTable",
                    workspaceConnectionId: wc,
                    catalog: "",
                    schema: "",
                    table: "",
                  };
                });
              }}
            >
              <SelectTrigger className="h-9 text-sm">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="unityCatalogTable">Unity Catalog</SelectItem>
                <SelectItem value="lakebaseProvisionedDatabase">
                  Lakebase
                </SelectItem>
                <SelectItem value="lakebaseAutoscaling">
                  Lakebase Autoscaling
                </SelectItem>
              </SelectContent>
            </Select>
          </div>

          <div>
            {targetTable.tableType === "lakebaseProvisionedDatabase" ? (
              <LakebaseTableSelectorFields
                value={{
                  instanceName: targetTable.instanceName,
                  database: targetTable.database,
                  catalog: targetTable.catalog,
                  schema: targetTable.schema,
                  table: targetTable.table,
                }}
                workspaceConnectionId={workspaceConnectionId}
                onChange={(next) =>
                  updateTargetTable((current) =>
                    current.tableType === "lakebaseProvisionedDatabase"
                      ? {
                          ...current,
                          instanceName: next.instanceName ?? "",
                          database: next.database ?? "",
                          catalog: next.catalog ?? "",
                          schema: next.schema ?? "",
                          table: next.table ?? "",
                        }
                      : current,
                  )
                }
              />
            ) : targetTable.tableType === "lakebaseAutoscaling" ? (
              <LakebaseAutoscalingTableSelectorFields
                value={{
                  projectId: targetTable.projectId,
                  branchId: targetTable.branchId,
                  endpointId: targetTable.endpointId,
                  database: targetTable.database,
                  catalog: targetTable.catalog,
                  schema: targetTable.schema,
                  table: targetTable.table,
                }}
                workspaceConnectionId={workspaceConnectionId}
                onChange={(next) =>
                  updateTargetTable((current) =>
                    current.tableType === "lakebaseAutoscaling"
                      ? {
                          ...current,
                          projectId: next.projectId ?? "",
                          branchId: next.branchId ?? "",
                          endpointId: next.endpointId ?? "",
                          database: next.database ?? "",
                          catalog: next.catalog ?? "",
                          schema: next.schema ?? "",
                          table: next.table ?? "",
                        }
                      : current,
                  )
                }
              />
            ) : (
              <UnityCatalogTableSelectorFields
                value={{
                  catalog: targetTable.catalog,
                  schema: targetTable.schema,
                  table: targetTable.table,
                }}
                workspaceConnectionId={workspaceConnectionId}
                onChange={(next) =>
                  updateTargetTable((current) =>
                    current.tableType === "unityCatalogTable"
                      ? {
                          ...current,
                          catalog: next.catalog ?? "",
                          schema: next.schema ?? "",
                          table: next.table ?? "",
                        }
                      : current,
                  )
                }
              />
            )}
          </div>
        </div>
      </div>

      <div className="rounded-md border border-border p-3 space-y-3">
        <div>
          <Label className="text-sm font-medium">Column Mapping</Label>
          <p className="text-xs text-muted-foreground">
            This phase only builds the strict mapping UI skeleton for
            SaveToTable.
          </p>
        </div>

        {loadingColumns && (
          <p className="text-xs text-muted-foreground">
            Loading target table columns...
          </p>
        )}
        {tableDetailsError && (
          <p className="text-xs text-destructive">{tableDetailsError}</p>
        )}
        {!loadingColumns &&
          !tableDetailsError &&
          targetColumns.length === 0 && (
            <p className="text-xs text-muted-foreground">
              Select a target table to load available target columns.
            </p>
          )}

        {targetColumns.length > 0 && (
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Target Column</TableHead>
                <TableHead>Column Handling</TableHead>
                <TableHead>Source Form Field</TableHead>
                <TableHead>Metadata</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {targetColumns.map((column) => {
                const columnName = column.name ?? "";
                const exclusion = saveToTableParams.excludedColumns.find(
                  (item) => item.columnName === columnName,
                );
                const mapping = saveToTableParams.columnMappings.find(
                  (item) => item.targetColumnName === columnName,
                );
                const columnMode = exclusion?.reason ?? MAP_COLUMN_VALUE;

                return (
                  <TableRow key={columnName}>
                    <TableCell>
                      <div className="font-medium">{columnName}</div>
                      <div className="text-xs text-muted-foreground">
                        {column.type ?? "unknown"}
                      </div>
                    </TableCell>
                    <TableCell>
                      <Select
                        value={columnMode}
                        onValueChange={(value) =>
                          updateColumnMode(
                            columnName,
                            value as
                              | typeof MAP_COLUMN_VALUE
                              | SaveToTableColumnOverrideReason,
                          )
                        }
                      >
                        <SelectTrigger className="h-9 text-sm">
                          <SelectValue />
                        </SelectTrigger>
                        <SelectContent>
                          {COLUMN_OVERRIDE_OPTIONS.map((option) => (
                            <SelectItem key={option.value} value={option.value}>
                              {option.label}
                            </SelectItem>
                          ))}
                        </SelectContent>
                      </Select>
                    </TableCell>
                    <TableCell>
                      <Select
                        value={
                          mapping?.formChildComponentCodeName ??
                          UNMAPPED_SOURCE_VALUE
                        }
                        disabled={columnMode !== MAP_COLUMN_VALUE}
                        onValueChange={(value) =>
                          updateColumnMapping(
                            columnName,
                            value === UNMAPPED_SOURCE_VALUE ? "" : value,
                          )
                        }
                      >
                        <SelectTrigger className="h-9 text-sm">
                          <SelectValue placeholder="Select form field..." />
                        </SelectTrigger>
                        <SelectContent>
                          <SelectItem value={UNMAPPED_SOURCE_VALUE}>
                            Unmapped
                          </SelectItem>
                          {sourceOptions.map((option) => (
                            <SelectItem key={option.value} value={option.value}>
                              {option.label}
                            </SelectItem>
                          ))}
                        </SelectContent>
                      </Select>
                    </TableCell>
                    <TableCell className="text-xs text-muted-foreground">
                      {columnMode === MAP_COLUMN_VALUE
                        ? column.nullable === false
                          ? "Required"
                          : "Nullable"
                        : `Excluded: ${columnMode}`}
                    </TableCell>
                  </TableRow>
                );
              })}
            </TableBody>
          </Table>
        )}
      </div>
    </div>
  );
};
