import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import type { SaveToTableParams } from "../../../../../types/workflow";
import SaveToTableColumnMappingEditor from "./SaveToTableColumnMappingEditor";

const params: SaveToTableParams = {
  sourceFormComponentCodeName: "orderForm",
  targetTable: {
    tableType: "unityCatalogTable",
    workspaceConnectionId: 1,
    catalog: "main",
    schema: "sales",
    table: "orders",
  },
  excludedColumns: [],
  columnMappings: [],
};

describe("SaveToTableColumnMappingEditor", () => {
  it("emits an exclusion reason when a target column is not mapped", async () => {
    const user = userEvent.setup();
    const onColumnModeChange = vi.fn();

    render(
      <SaveToTableColumnMappingEditor
        params={params}
        columns={[{ name: "created_at", type: "TIMESTAMP", nullable: false }]}
        sourceOptions={[
          { value: "orderId", label: "orderId", description: "TextInput" },
        ]}
        isLoading={false}
        errorMessage={null}
        onColumnModeChange={onColumnModeChange}
        onColumnMappingChange={vi.fn()}
      />,
    );

    await user.click(
      screen.getByRole("combobox", {
        name: "Column handling for created_at",
      }),
    );
    await user.click(
      await screen.findByRole("option", { name: "Autogenerated" }),
    );

    expect(onColumnModeChange).toHaveBeenCalledWith("created_at", "autogenerated");
  });

  it("emits the selected form field for a mapped target column", async () => {
    const user = userEvent.setup();
    const onColumnMappingChange = vi.fn();

    render(
      <SaveToTableColumnMappingEditor
        params={params}
        columns={[{ name: "order_id", type: "STRING", nullable: false }]}
        sourceOptions={[
          { value: "orderId", label: "orderId", description: "TextInput" },
        ]}
        isLoading={false}
        errorMessage={null}
        onColumnModeChange={vi.fn()}
        onColumnMappingChange={onColumnMappingChange}
      />,
    );

    await user.click(
      screen.getByRole("combobox", {
        name: "Source form field for order_id",
      }),
    );
    await user.click(await screen.findByRole("option", { name: "orderId" }));

    expect(onColumnMappingChange).toHaveBeenCalledWith("order_id", "orderId");
  });
});
